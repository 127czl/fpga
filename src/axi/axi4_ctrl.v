module axi4_ctrl #(
	parameter 	C_ID_LEN      = 8, 
			C_DATA_LEN    = 128, 
			C_DATA_SIZE   = 4, 	//	C_DATA_LEN=8:0, 16:1, 32:2, 64:3, 128:4, 256:5, 512:6, 1024:7
			
			C_BURST_LEN   = 128,
			
			C_STRB_LEN    = C_DATA_LEN / 8, 
			C_ADDR_INC    = C_BURST_LEN * C_STRB_LEN,
			
			C_BASE_ADDR   = 32'h00000000, 	//	Start at 0x00000000 by default
			C_BUF_SIZE    = 22, 			//	Allocate 2^22 bytes (4MB) by default. The module takes 4*4MB by default. 
			C_RD_END_ADDR = 1280 * 720,
			C_FRAME_BITS  = 7,				//	128 frame slots in the DDR ring
			C_FRAME_COUNT = 128,
			C_RECORD_FRAMES = 104,			//	0..103 preserved recording region
			C_LIVE_BASE   = 104,			//	104..111 live preview ring
			C_LIVE_FRAMES = 8,
			//	112..127 snapshots
			
			C_W_WIDTH     = 64, 
			C_R_WIDTH     = 8
)(
    input  wire                 axi_clk         ,
    input  wire                 axi_reset       ,
    input  wire                 frame_hold      ,
    input  wire                 read_ext_en     ,
    input  wire     [C_FRAME_BITS-1:0] read_index,
    input  wire                 record_region   ,
    input  wire                 read_flush      ,
    input  wire                 ring_clear      ,
    input  wire                 snapshot_req    ,
    input  wire     [C_FRAME_BITS-1:0] snapshot_slot,
    output reg                  write_freeze    ,
    output reg  [C_FRAME_BITS-1:0] last_frame_index,
    output reg                  snapshot_toggle ,
    
    output       [C_ID_LEN-1:0]      axi_awid        ,
    output       [31:0]      axi_awaddr      ,
    output       [ 7:0]      axi_awlen       ,
    output       [ 2:0]      axi_awsize      ,
    output       [ 1:0]      axi_awburst     ,
    output                   axi_awlock      ,
    output       [ 3:0]      axi_awcache     ,
    output       [ 2:0]      axi_awprot      ,
    output       [ 3:0]      axi_awqos       ,
    output reg                  axi_awvalid     ,
    input  wire                 axi_awready     ,
    
    output       [C_DATA_LEN-1:0]      axi_wdata       ,
    output       [C_STRB_LEN-1:0]      axi_wstrb       ,
    output                   axi_wlast       ,
    output reg                  axi_wvalid      ,
    input  wire                 axi_wready      ,
    
    input  wire     [C_ID_LEN-1:0]      axi_bid         ,
    input  wire     [ 1:0]      axi_bresp       ,
    input  wire                 axi_bvalid      ,
    output                   axi_bready      ,
    
    output       [C_ID_LEN-1:0]      axi_arid        ,
    output       [31:0]      axi_araddr      ,
    output       [ 7:0]      axi_arlen       ,
    output       [ 2:0]      axi_arsize      ,
    output       [ 1:0]      axi_arburst     ,
    output                   axi_arlock      ,
    output       [ 3:0]      axi_arcache     ,
    output       [ 2:0]      axi_arprot      ,
    output       [ 3:0]      axi_arqos       ,
    output reg                  axi_arvalid     ,
    input  wire                 axi_arready     ,
    
    input  wire     [C_ID_LEN-1:0]      axi_rid         ,
    input  wire     [C_DATA_LEN-1:0]      axi_rdata       ,
    input  wire     [ 1:0]      axi_rresp       ,
    input  wire                 axi_rlast       ,
    input  wire                 axi_rvalid      ,
    output                   axi_rready      ,
    
    input  wire                 wframe_pclk     ,
    input  wire                 wframe_vsync    ,		//	Writter VSync. Flush on falling edge. Connect to EOF. 
    input  wire                 wframe_data_en  ,
    input  wire     [C_W_WIDTH-1:0]      wframe_data     ,
    
    input  wire                 rframe_pclk     ,
    input  wire                 rframe_vsync    ,		//	Reader VSync. Flush on falling edge. Connect to ~EOF. 
    input  wire                 rframe_data_en  ,
    output wire     [C_R_WIDTH-1:0]      rframe_data     ,
    
    output 		[31:0] 	tp_o
);
	
	initial begin
		axi_awvalid <= 0; 
		axi_wvalid <= 0; 
		axi_arvalid <= 0; 
	end

	assign axi_awid    = {C_ID_LEN{1'b0}};
	assign axi_awlen   = C_BURST_LEN - 1'b1;
	assign axi_awsize  = C_DATA_SIZE;
	assign axi_awburst = 2'b01;	//	INCR
	assign axi_awlock  = 1'b0;
	assign axi_awcache = 0;
	assign axi_awprot  = 3'b0;
	assign axi_awqos   = 4'b0;
	assign axi_wstrb   = 32'hFFFFFFFF;
	assign axi_bready  = 1; 
	    
	assign axi_arid    = {C_ID_LEN{1'b0}};
	assign axi_arlen   = C_BURST_LEN - 1'b1;
	assign axi_arsize  = C_DATA_SIZE;
	assign axi_arburst = 2'b01;	//	INCR
	assign axi_arlock  = 1'b0;
	assign axi_arcache = 0;
	assign axi_arprot  = 3'b0;
	assign axi_arqos   = 4'b0;
	assign axi_rready  = 1; 
	
	
	
	
	////////////////////////////////////////////////////////////////
	//	R/W Schedule
	reg	[C_FRAME_BITS-1:0] 	rc_wframe_index;
	reg	[C_FRAME_BITS-1:0] 	rc_rframe_index;
	reg	[C_FRAME_BITS-1:0] 	r_last_completed;
	reg	[1:0] 				r_frame_hold_sync;
	reg	[1:0] 				r_read_ext_en_sync;
	reg	[1:0] 				r_record_region_sync;
	reg	[1:0] 				r_read_flush_sync;
	reg	[C_FRAME_BITS-1:0] 	r_read_index_s1;
	reg	[C_FRAME_BITS-1:0] 	r_read_index_s2;
	reg	[1:0] 				r_ring_clear_sync;
	reg						r_frame_hold_d;
	reg						r_freeze_latched;
	reg						r_write_region;
	reg						r_snapshot_active;
	reg	[C_FRAME_BITS-1:0] 	r_snapshot_slot;
	reg 						r_wframe_inc = 0, r_rframe_inc = 0;

	always @(posedge axi_clk) begin
		if(axi_reset) begin
			r_frame_hold_sync  <= 2'b00;
			r_read_ext_en_sync <= 2'b00;
			r_record_region_sync <= 2'b00;
			r_read_flush_sync <= 2'b00;
			r_read_index_s1    <= {C_FRAME_BITS{1'b0}};
			r_read_index_s2    <= {C_FRAME_BITS{1'b0}};
			r_ring_clear_sync  <= 2'b00;
		end else begin
			r_frame_hold_sync  <= {r_frame_hold_sync[0], frame_hold};
			r_read_ext_en_sync <= {r_read_ext_en_sync[0], read_ext_en};
			r_record_region_sync <= {r_record_region_sync[0], record_region};
			r_read_flush_sync <= {r_read_flush_sync[0], read_flush};
			r_read_index_s1    <= read_index;
			r_read_index_s2    <= r_read_index_s1;
			r_ring_clear_sync  <= {r_ring_clear_sync[0], ring_clear};
		end
	end

	wire frame_hold_axi  = r_frame_hold_sync[1];
	wire read_ext_axi    = r_read_ext_en_sync[1];
	wire record_region_axi = r_record_region_sync[1];
	wire read_flush_axi    = r_read_flush_sync[1];
	wire ring_clear_axi  = r_ring_clear_sync[1];

	// A pause / compare request stops the writer only after the current frame
	// has completed.  Latching on the writer's EOF pulse guarantees that all
	// four DDR frame buffers contain complete pictures when the read pointer is
	// frozen.  Gating the writer makes pause and multi-frame compare stable
	// instead of allowing the live acquisition to overwrite the frozen frame
	// after four frames.
	always @(posedge axi_clk) begin
		if(axi_reset) begin
			r_frame_hold_d  <= 1'b0;
			r_freeze_latched <= 1'b0;
			write_freeze    <= 1'b0;
		end else begin
			r_frame_hold_d <= frame_hold_axi;
			if(!frame_hold_axi)
				r_freeze_latched <= 1'b0;
			else if(r_wframe_inc)
				r_freeze_latched <= 1'b1;
			write_freeze <= r_freeze_latched;
		end
	end

	// Ring pointers.  Write advances once per captured frame.  Live read
	// follows the last completed write buffer; external read mode is used for
	// snapshot compare and video playback.
	wire [C_FRAME_BITS-1:0] w_region_base =
		r_write_region ? {C_FRAME_BITS{1'b0}} : C_LIVE_BASE[C_FRAME_BITS-1:0];
	wire [C_FRAME_BITS-1:0] w_region_last =
		r_write_region ? (C_RECORD_FRAMES - 1) :
		                    (C_LIVE_BASE + C_LIVE_FRAMES - 1);
	wire [C_FRAME_BITS-1:0] w_input_base =
		record_region_axi ? {C_FRAME_BITS{1'b0}} : C_LIVE_BASE[C_FRAME_BITS-1:0];
	always @(posedge axi_clk) begin
		if(axi_reset) begin
			rc_wframe_index <= w_input_base;
			rc_rframe_index <= w_input_base;
			r_last_completed <= w_input_base;
			last_frame_index <= w_input_base;
			r_snapshot_active <= 1'b0;
			r_snapshot_slot   <= {C_FRAME_BITS{1'b0}};
			snapshot_toggle   <= 1'b0;
			r_write_region    <= record_region_axi;
		end else if(ring_clear_axi) begin
			rc_wframe_index <= w_input_base;
			rc_rframe_index <= w_input_base;
			r_last_completed <= w_input_base;
			last_frame_index <= w_input_base;
			r_snapshot_active <= 1'b0;
			r_snapshot_slot   <= {C_FRAME_BITS{1'b0}};
			r_write_region    <= record_region_axi;
		end else begin
			rc_wframe_index <= rc_wframe_index;
			rc_rframe_index <= rc_rframe_index;

			if(r_wframe_inc) begin
				if(r_snapshot_active) begin
					// This EOF belongs to the protected snapshot frame.
					r_snapshot_active <= 1'b0;
					snapshot_toggle   <= ~snapshot_toggle;
				end else begin
					if(record_region_axi == r_write_region) begin
						// Arm the next frame as a snapshot when a request arrived
						// during the frame that just completed.  Arming at EOF
						// guarantees the first data burst of the next frame is
						// already directed to the protected slot.
						if(snapshot_req) begin
							r_snapshot_active <= 1'b1;
							r_snapshot_slot   <= snapshot_slot;
						end
						r_last_completed <= rc_wframe_index;
						last_frame_index <= rc_wframe_index;
						if(rc_wframe_index == w_region_last)
							rc_wframe_index <= w_region_base;
						else
							rc_wframe_index <= rc_wframe_index + 1'b1;
					end else begin
						// Region changes are frame-aligned.  Finish the old
						// frame, then start the new region at its first slot.
						r_write_region <= record_region_axi;
						rc_wframe_index <= w_input_base;
					end
				end
			end

			if(r_rframe_inc) begin
				if(read_ext_axi)
					rc_rframe_index <= r_read_index_s2;
				else if(!frame_hold_axi)
					rc_rframe_index <= r_last_completed;
			end
		end
	end
	
	
	
	////////////////////////////////////////////////////////////////
	//	AXI Writter

	wire 				w_wfifo_pempty, w_wfifo_empty; 
	wire 				w_wfifo_ren; 
	wire 	[C_DATA_LEN-1:0] 	w_wfifo_rdata; 

	//	On EOF when ~empty, flush the last data then reset FIFO. 
	reg 	[3:0] 	rs_w = 0; 
	wire 	[3:0] 	ws_w_idle = 0; 
	wire 	[3:0] 	ws_w_wdata = 1; 
	wire 	[3:0] 	ws_w_winc = 2; 
	wire 	[3:0] 	ws_w_eof = 3; 

	//	Write Pointer. Burst bytes is always C_ADDR_INC. 
	reg 	[C_BUF_SIZE-1:0] 	rc_w_ptr = 0; 
	reg 	[0:0] 		rc_w_eof = 0; 
	reg 				r_w_rst = 1; 
	
	//	Burst Control
	reg 	[7:0] 	rc_burst = 0; 	//	Compare to C_BURST_LEN - 1. 
	
	//	EOF Monitor. 
	reg 	[1:0] 	r_wframe_sync = 0; 	
	reg 			r_weof_pending = 0; 

	always @(posedge axi_clk or posedge axi_reset) begin
		if(axi_reset) begin
			rs_w <= 0; 
			rc_w_ptr <= 0; 
			rc_w_eof <= 0; 
			r_w_rst <= 1; 
			axi_awvalid <= 0; 
			axi_wvalid <= 0; 
			r_wframe_sync <= 0; 
			r_weof_pending <= 0; 
			r_wframe_inc <= 0; 
			
		end else if(write_freeze) begin
			// Hold the already completed DDR image set.  The camera-side data
			// gate is asserted from this signal, and the write FIFO is kept in
			// reset so stale pixels cannot leak into a buffer when playback
			// resumes.
			rs_w         <= ws_w_idle;
			rc_w_ptr     <= rc_w_ptr;
			rc_w_eof     <= 1'b0;
			r_w_rst      <= 1'b1;
			axi_awvalid  <= 1'b0;
			axi_wvalid   <= 1'b0;
			r_wframe_inc <= 1'b0;
			r_wframe_sync <= {r_wframe_sync[0], wframe_vsync};
			r_weof_pending <= 1'b0;
		end else begin
			rc_w_eof <= 0; 
			r_wframe_inc <= 0; 
			
			//	Raise EOF on falling edge of VSYNC. 
			r_wframe_sync <= {r_wframe_sync, wframe_vsync}; 
			if(r_wframe_sync == 2'b10) begin
				r_weof_pending <= 1; 
			end else begin
			end
			
			if(axi_awready) begin
				axi_awvalid <= 0; 
			end else begin
			end
			
			case (rs_w)
				ws_w_idle: begin
						rc_burst <= 0; 
						r_w_rst <= 0; 
						
						if(~w_wfifo_pempty) begin
							axi_awvalid <= 1; 
							axi_wvalid <= 1; 
							rs_w <= ws_w_wdata; 
						
						end else if(r_weof_pending && (~w_wfifo_empty)) begin
							//	There's some data in the FIFO. write last. 
							axi_awvalid <= 1; 
							axi_wvalid <= 1; 
							rs_w <= ws_w_wdata; 
							
						end else if(r_weof_pending) begin
							//	EOF. Reset FIFO. Increment write pointer. 
							r_w_rst <= 1; 
							r_wframe_inc <= 1; 
							rs_w <= ws_w_eof; 
							
						end else begin
						end
					end
					
				ws_w_eof: begin
						//	Wait for some cycles to release reset. 
						r_weof_pending <= 0; 
						rc_w_ptr <= 0; 
						
						rc_w_eof <= rc_w_eof + 1; 
						if(&rc_w_eof)
							rs_w <= ws_w_idle; 
						else begin
						end
					end
					
				ws_w_wdata: begin
						rc_burst <= rc_burst + axi_wready; 
						
						//	On last transaction terminate write. 
						if(axi_wlast && axi_wready) begin
							axi_wvalid <= 0; 
							rs_w <= ws_w_winc; 
						end else begin
						end
					end
					
				ws_w_winc: begin
						rc_w_ptr <= rc_w_ptr + C_ADDR_INC; 
						rs_w <= ws_w_idle; 
					end
			endcase
		end
	end
	assign axi_awaddr = C_BASE_ADDR +
	                    {(r_snapshot_active ? r_snapshot_slot : rc_wframe_index), rc_w_ptr};
	assign axi_wdata = w_wfifo_rdata; 
	assign axi_wlast = (rc_burst >= C_BURST_LEN - 1); 
	
	assign w_wfifo_ren = axi_wvalid && axi_wready; 
	
	
	assign tp_o[1:0] = {rs_w[1:0]}; 
	assign tp_o[2] = axi_wvalid; 
	assign tp_o[3] = wframe_data_en; 
	
	
	generate
		if(C_W_WIDTH == 64) begin: Gen_FIFO_W64
			W0_FIFO_64 u_W0_FIFO_64 
			(
			    .wr_clk_i       (wframe_pclk    ),
			    .wr_en_i        (wframe_data_en),
			    .wdata          (wframe_data    ),
			    
			    .a_rst_i 	(r_w_rst), 

			    .rd_clk_i       (axi_clk        ),
			    .rd_en_i        (w_wfifo_ren     ),
			    .rdata          (w_wfifo_rdata    ),
			    .prog_empty_o	(w_wfifo_pempty),
			    .empty_o 		(w_wfifo_empty)
			);
		end else if(C_W_WIDTH == 32) begin: Gen_FIFO_W32
			W0_FIFO_32 u_W0_FIFO_32
			(
			    .wr_clk_i       (wframe_pclk    ),
			    .wr_en_i        (wframe_data_en),
			    .wdata          (wframe_data    ),
			    
			    .a_rst_i 	(r_w_rst), 

			    .rd_clk_i       (axi_clk        ),
			    .rd_en_i        (w_wfifo_ren     ),
			    .rdata          (w_wfifo_rdata    ),
			    .prog_empty_o	(w_wfifo_pempty),
			    .empty_o 		(w_wfifo_empty)
			);
		end else if(C_W_WIDTH == 8) begin: Gen_FIFO_W8
			W0_FIFO_8 u_W0_FIFO_8 
			(
			    .wr_clk_i       (wframe_pclk    ),
			    .wr_en_i        (wframe_data_en),
			    .wdata          (wframe_data    ),
			    
			    .a_rst_i 	(r_w_rst), 

			    .rd_clk_i       (axi_clk        ),
			    .rd_en_i        (w_wfifo_ren     ),
			    .rdata          (w_wfifo_rdata    ),
			    .prog_empty_o	(w_wfifo_pempty),
			    .empty_o 		(w_wfifo_empty)
			);
		end
	endgenerate




















reg                             rframe_vsync_dly;

always @(posedge rframe_pclk)
begin
    if(axi_reset == 1'b1)
        rframe_vsync_dly <= 1'b0;
    else
        rframe_vsync_dly <= rframe_vsync;
end

wire                            rframe_vsync_neg;
assign rframe_vsync_neg =  rframe_vsync_dly & ~rframe_vsync;

reg             [4:0]           rfifo_cnt;

always @(posedge rframe_pclk)
begin
    if(axi_reset == 1'b1)
        rfifo_cnt <= 5'h1f;
    else
    begin
        if(rframe_vsync_neg == 1'b1)
            rfifo_cnt <= 5'h1f;
        else if(rfifo_cnt > 5'd0)
            rfifo_cnt <= rfifo_cnt - 1'b1;
        else
            rfifo_cnt <= 5'b0;
    end
end

reg                             rfifo_rst;

always @(posedge rframe_pclk)
begin
    if(axi_reset == 1'b1)
        rfifo_rst <= 1'b1;
    else
    begin
        if(rfifo_cnt == 5'b0)
            rfifo_rst <= 1'b0;
        else
            rfifo_rst <= 1'b1;
    end
end


wire 			w_rfifo_rst = axi_reset || rfifo_rst || read_flush_axi; 

reg                             rfifo_wenb;
reg             [C_DATA_LEN-1:0]          rfifo_wdata;
wire            [ 9:0]          rfifo_wcnt;
wire 					  rfifo_wfull; 
wire                            rfifo_wr_rst_busy;
wire 					w_rfifo_aempty; 
wire 					w_rfifo_empty; 


generate
	if(C_R_WIDTH == 8) begin: Gen_RFIFO_8
		R0_FIFO_8 u_R0_FIFO_8
		(
			.wr_clk_i		(axi_clk),
			.wr_en_i		(rfifo_wenb),
			.wdata			(rfifo_wdata),
			.a_rst_i		(w_rfifo_rst), 
			.prog_full_o		(rfifo_wfull),
			
			.rd_clk_i		(rframe_pclk),
			.rd_en_i		(rframe_data_en),
			.rdata			(rframe_data),
			.empty_o		(w_rfifo_empty),
			.almost_empty_o	(w_rfifo_aempty)
		);
	end else if(C_R_WIDTH == 16) begin: Gen_RFIFO_16	
		R0_FIFO_16 u_R0_FIFO_16
		(
			.wr_clk_i		(axi_clk),
			.wr_en_i		(rfifo_wenb),
			.wdata			(rfifo_wdata),
			.a_rst_i		(w_rfifo_rst), 
			.prog_full_o		(rfifo_wfull),
			
			.rd_clk_i		(rframe_pclk),
			.rd_en_i		(rframe_data_en),
			.rdata			(rframe_data),
			.empty_o		(w_rfifo_empty),
			.almost_empty_o	(w_rfifo_aempty)
		);
	end
endgenerate
		
reg r_rfifo_rst = 0; 
always @(posedge axi_clk)
begin
	r_rfifo_rst <= w_rfifo_rst; 
end

//assign tp_o[7:0] = {w_rfifo_empty, rfifo_wfull, rframe_data_en, rfifo_wenb, rfifo_rst, axi_reset, rframe_pclk, axi_clk}; 

reg             [15:0]               rfifo_wr_rst_busy_dly = 2'b0;

always @(posedge axi_clk or posedge r_rfifo_rst)
begin
    if(r_rfifo_rst == 1'b1)
        rfifo_wr_rst_busy_dly <= 0;
    else
        rfifo_wr_rst_busy_dly <= {rfifo_wr_rst_busy_dly,1'b1};
end

wire                                rfifo_wr_rst_busy_neg;
assign rfifo_wr_rst_busy_neg = (rfifo_wr_rst_busy_dly[1:0] == 2'b01) ? 1'b1 : 1'b0;

reg             [4:0]               read_ddr_delay_cnt;

always @(posedge axi_clk or posedge r_rfifo_rst)
begin
    if(r_rfifo_rst == 1'b1)
        read_ddr_delay_cnt <= 5'b0;
    else
    begin
        if(rfifo_wr_rst_busy_neg == 1'b1)
            read_ddr_delay_cnt <= 5'd31;
        else if(read_ddr_delay_cnt > 5'b0)
            read_ddr_delay_cnt <= read_ddr_delay_cnt - 1'b1;
        else
            read_ddr_delay_cnt <= 5'b0;
    end
end

always @(posedge axi_clk or posedge axi_reset) begin
	if(axi_reset)
		r_rframe_inc <= 0; 
	else
		r_rframe_inc <= rfifo_wr_rst_busy_neg; 
end


wire                                read_ddr_init_flag;
assign read_ddr_init_flag = (read_ddr_delay_cnt == 5'd1) ? 1'b1 : 1'b0;

